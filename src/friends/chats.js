let last = {};
// one of a friend's calls, not the same one twice in a row
export function chat(id) {
  const list = CHATS[id] || [];
  if (!list.length) return [];
  let k = Math.floor(Math.random() * list.length);
  if (list.length > 1 && k === last[id]) k = (k + 1) % list.length;
  last[id] = k;
  return list[k];
}
