let LANG = 'he';
try { LANG = localStorage.getItem('kotc_lang') || 'he'; } catch (e) {}
if (!I18N[LANG]) LANG = 'he';

function t(key, vars) {
  let s = I18N[LANG][key];
  if (s === undefined) s = I18N.he[key];
  if (typeof s === 'string' && vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
}
function setLang(l) {
  LANG = l;
  try { localStorage.setItem('kotc_lang', l); } catch (e) {}
  applyLang();
}
function applyLang() {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === 'he' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('.lang-toggle').forEach(b => { b.textContent = LANG === 'he' ? 'EN' : 'עב'; });
  document.title = t('title');
}
