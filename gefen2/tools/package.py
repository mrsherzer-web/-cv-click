#!/usr/bin/env python3
"""
Packaging for GEFEN 2. Run from anywhere:

  python3 gefen2/tools/package.py sw          -> gefen2/sw.js (offline cache list for the installable web app)
  python3 gefen2/tools/package.py html        -> dist/gefen2.html (the whole game in ONE file, opens by double click)
  python3 gefen2/tools/package.py zip         -> dist/gefen2-web.zip (upload this to Game Jolt / itch.io as an HTML game)
  python3 gefen2/tools/package.py all         -> everything above

"html" needs esbuild: set ESBUILD=/path/to/esbuild, or have it on PATH, or `npm i esbuild` next to the repo.
"""
import base64
import hashlib
import json
import mimetypes
import os
import re
import shutil
import subprocess
import sys
import tempfile
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # gefen2/
REPO = os.path.dirname(ROOT)
DIST = os.path.join(REPO, "dist")
mimetypes.add_type("image/webp", ".webp")
mimetypes.add_type("font/woff2", ".woff2")
mimetypes.add_type("audio/mpeg", ".mp3")
mimetypes.add_type("video/mp4", ".mp4")
mimetypes.add_type("video/webm", ".webm")
SKIP_DIRS = {"source", "hf", "__pycache__"}


def runtime_files():
    """Every file the game needs at run time, relative to gefen2/."""
    out = ["index.html", "manifest.webmanifest"]
    for top in ("css", "src", "vendor", "assets"):
        for base, dirs, files in os.walk(os.path.join(ROOT, top)):
            dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
            for f in sorted(files):
                rel = os.path.relpath(os.path.join(base, f), ROOT).replace(os.sep, "/")
                if f.startswith(".") or f.endswith((".json", ".py", ".md")) or rel.startswith("src/dev/worldview"):
                    continue
                out.append(rel)
    return out


def build_sw():
    files = runtime_files()
    h = hashlib.sha1()
    for f in files:
        h.update(f.encode())
        h.update(open(os.path.join(ROOT, f), "rb").read())
    sw = (
        "// Offline support: the whole game is cached on first visit, so the installed app works\n"
        "// without internet. Generated by tools/package.py sw - run it again after changing game files.\n"
        f"const VERSION = 'gefen2-{h.hexdigest()[:10]}';\n"
        "const FILES = " + json.dumps(["./"] + files, indent=2) + ";\n\n"
        "self.addEventListener('install', (e) => {\n"
        "  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));\n"
        "});\n"
        "self.addEventListener('activate', (e) => {\n"
        "  e.waitUntil(\n"
        "    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('gefen2-') && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim()),\n"
        "  );\n"
        "});\n"
        "self.addEventListener('fetch', (e) => {\n"
        "  if (e.request.method !== 'GET') return;\n"
        "  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));\n"
        "});\n"
    )
    with open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8") as f:
        f.write(sw)
    print("wrote gefen2/sw.js", len(files), "files")


def data_uri(path):
    mime = mimetypes.guess_type(path)[0] or "application/octet-stream"
    with open(path, "rb") as f:
        return f"data:{mime};base64," + base64.b64encode(f.read()).decode()


def esbuild():
    for c in (os.environ.get("ESBUILD"), shutil.which("esbuild"), os.path.join(REPO, "node_modules", ".bin", "esbuild")):
        if c and os.path.exists(c):
            return [c]
    return ["npx", "esbuild@0.25.10"]


def build_html():
    os.makedirs(DIST, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        js_out = os.path.join(tmp, "game.js")
        subprocess.run(esbuild() + [os.path.join(ROOT, "src", "main.js"), "--bundle", "--format=iife", "--minify", "--target=es2020", "--log-level=error", "--outfile=" + js_out], check=True)
        js = open(js_out, encoding="utf-8").read()
    fonts = open(os.path.join(ROOT, "css", "fonts.css"), encoding="utf-8").read()
    fonts = re.sub(r"url\('\.\./(assets/fonts/[^']+)'\)", lambda m: f"url('{data_uri(os.path.join(ROOT, m.group(1)))}')", fonts)
    style = open(os.path.join(ROOT, "css", "style.css"), encoding="utf-8").read()
    # everything under assets/ that the game asks for through url(): images, video, sound
    embed = {}
    for sub in ("img", "video", "audio"):
        d = os.path.join(ROOT, "assets", sub)
        for base, _, files in os.walk(d):
            for f in sorted(files):
                if f.endswith(".json"):
                    continue
                p = os.path.join(base, f)
                embed[os.path.relpath(p, os.path.join(ROOT, "assets")).replace(os.sep, "/")] = data_uri(p)
    html = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
    html = re.sub(r'\s*<link rel="stylesheet" href="css/fonts.css" />', "", html)
    html = re.sub(r'\s*<link rel="manifest" href="manifest.webmanifest" />', "", html)
    icon = data_uri(os.path.join(ROOT, "assets", "icon-192.png"))
    html = html.replace('<link rel="apple-touch-icon" href="assets/icon-192.png" />', f'<link rel="apple-touch-icon" href="{icon}" />')
    html = html.replace('<link rel="stylesheet" href="css/style.css" />', f"<style>\n{fonts}\n{style}\n</style>")
    boot = "<script>window.__EMBED = " + json.dumps(embed) + ";</script>\n"
    js = js.replace("</script", "<\\/script")
    tag = '<script type="module" src="src/main.js"></script>'
    assert tag in html
    html = html.replace(tag, boot + "<script>\n" + js + "\n</script>")
    out = os.path.join(DIST, "gefen2.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(html)
    print("wrote", out, f"{os.path.getsize(out) / 1e6:.1f} MB")
    return out


def build_zip():
    os.makedirs(DIST, exist_ok=True)
    build_sw()
    out = os.path.join(DIST, "gefen2-web.zip")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in runtime_files() + ["sw.js"]:
            z.write(os.path.join(ROOT, f), f)
    print("wrote", out, f"{os.path.getsize(out) / 1e6:.1f} MB")
    return out


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("sw", "all"):
        build_sw()
    if what in ("html", "all"):
        build_html()
    if what in ("zip", "all"):
        build_zip()
